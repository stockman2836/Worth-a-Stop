import { readFile, writeFile } from 'node:fs/promises';
import { iconNames } from '../web/icons.mjs';

const symbols = [];
for (const name of iconNames) {
  const source = await readFile(new URL(`../node_modules/lucide-static/icons/${name}.svg`, import.meta.url), 'utf8');
  const body = source.match(/<svg\b[^>]*>([\s\S]*?)<\/svg>/)?.[1];
  if (!body) throw Error(`Invalid SVG: ${name}`);
  symbols.push(`<symbol id="${name}" viewBox="0 0 24 24">${body.trim()}</symbol>`);
}
const sprite = `<!-- Generated by npm run icons:build from lucide-static. See /icons.LICENSE.txt. -->\n<svg xmlns="http://www.w3.org/2000/svg"><defs>\n${symbols.join('\n')}\n</defs></svg>\n`;
await writeFile(new URL('../web/icons.svg', import.meta.url), sprite);
await writeFile(new URL('../web/icons.LICENSE.txt', import.meta.url), await readFile(new URL('../node_modules/lucide-static/LICENSE', import.meta.url)));
console.log(`Built ${symbols.length} icons (${Buffer.byteLength(sprite)} bytes).`);
